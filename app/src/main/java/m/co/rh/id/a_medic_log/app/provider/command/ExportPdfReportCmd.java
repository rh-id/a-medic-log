package m.co.rh.id.a_medic_log.app.provider.command;

import java.io.File;
import java.text.SimpleDateFormat;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.Date;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ExecutorService;

import io.reactivex.rxjava3.core.Single;
import io.reactivex.rxjava3.schedulers.Schedulers;
import m.co.rh.id.a_medic_log.app.provider.component.AdherenceReportGenerator;
import m.co.rh.id.a_medic_log.app.provider.component.PdfReportData;
import m.co.rh.id.a_medic_log.app.provider.component.PdfReportExporter;
import m.co.rh.id.a_medic_log.base.dao.MedicineDao;
import m.co.rh.id.a_medic_log.base.dao.MedicineIntakeDao;
import m.co.rh.id.a_medic_log.base.dao.MedicineReminderDao;
import m.co.rh.id.a_medic_log.base.dao.ProfileDao;
import m.co.rh.id.a_medic_log.base.entity.Medicine;
import m.co.rh.id.a_medic_log.base.entity.MedicineIntake;
import m.co.rh.id.a_medic_log.base.entity.MedicineReminder;
import m.co.rh.id.a_medic_log.base.entity.Profile;
import m.co.rh.id.a_medic_log.base.provider.FileHelper;
import m.co.rh.id.aprovider.Provider;
import m.co.rh.id.aprovider.ProviderValue;

/**
 * Generates a per-profile PDF medication report: a medications table with the
 * medicines' schedules, the 7-day and 30-day adherence summaries (via
 * {@link AdherenceReportGenerator}) and the profile's intake history of the
 * selected range.
 * The file name never contains the profile name (a name with a path separator
 * would break the real-file write), a fixed timestamped name is used instead.
 */
public class ExportPdfReportCmd {
    private static final String PDF_FILE_NAME_PREFIX = "medication-report-";
    private static final String PDF_FILE_NAME_SUFFIX = ".pdf";
    private static final String PDF_FILE_NAME_TIMESTAMP_FORMAT = "yyyyMMdd_HHmmss";

    private static final int ADHERENCE_RANGE_7_DAYS = 7;
    private static final int ADHERENCE_RANGE_30_DAYS = 30;

    protected ProviderValue<PdfReportExporter> mPdfReportExporter;
    protected ExecutorService mExecutorService;
    protected FileHelper mFileHelper;
    protected ProfileDao mProfileDao;
    protected MedicineDao mMedicineDao;
    protected MedicineReminderDao mMedicineReminderDao;
    protected MedicineIntakeDao mMedicineIntakeDao;
    protected ProviderValue<AdherenceReportGenerator> mAdherenceReportGenerator;

    /**
     * The report file generated by the last successful run, deleted (together
     * with its now-empty temp directory) before the next one is created.
     * Safe as an instance field because this command is a root-provider
     * lazy singleton.
     */
    private File mPreviousReportFile;

    public ExportPdfReportCmd(Provider provider) {
        mPdfReportExporter = provider.lazyGet(PdfReportExporter.class);
        mExecutorService = provider.get(ExecutorService.class);
        mFileHelper = provider.get(FileHelper.class);
        mProfileDao = provider.get(ProfileDao.class);
        mMedicineDao = provider.get(MedicineDao.class);
        mMedicineReminderDao = provider.get(MedicineReminderDao.class);
        mMedicineIntakeDao = provider.get(MedicineIntakeDao.class);
        mAdherenceReportGenerator = provider.lazyGet(AdherenceReportGenerator.class);
    }

    /**
     * Generate the PDF medication report of a single profile.
     *
     * @param profileId       id of the profile to report
     * @param intakeRangeDays intake-history range in days (e.g. 7, 30 or 90)
     * @return Single of the created report temp file
     */
    public Single<File> execute(long profileId, int intakeRangeDays) {
        // both adherence reports are generated inside the callable and the
        // explicit subscribeOn pins the whole generation, assembly and render
        // onto this command's executor thread
        return Single.fromCallable(() -> generateReport(profileId, intakeRangeDays,
                mAdherenceReportGenerator.get().generate(profileId,
                        Arrays.asList(ADHERENCE_RANGE_7_DAYS, ADHERENCE_RANGE_30_DAYS))))
                .subscribeOn(Schedulers.from(mExecutorService));
    }

    private File generateReport(long profileId, int intakeRangeDays,
                                List<AdherenceReport> adherenceReports) throws Exception {
        // the reports are by position: index 0 is the 7-day, index 1 the 30-day range
        AdherenceReport adherence7Days = adherenceReports.get(0);
        AdherenceReport adherence30Days = adherenceReports.get(1);
        Profile profile = mProfileDao.findProfileById(profileId);
        if (profile == null) {
            throw new IllegalArgumentException("Profile not found for id: " + profileId);
        }
        Date now = new Date();
        long rangeStart = AdherenceCalculator.rangeStart(now, intakeRangeDays);
        long rangeEnd = AdherenceCalculator.rangeEnd(now);
        PdfReportData reportData = assembleReportData(profile, adherence7Days,
                adherence30Days, rangeStart, rangeEnd);
        deletePreviousReport();
        File outFile = mFileHelper.createTempFile(PDF_FILE_NAME_PREFIX
                + new SimpleDateFormat(PDF_FILE_NAME_TIMESTAMP_FORMAT, Locale.getDefault())
                .format(now) + PDF_FILE_NAME_SUFFIX);
        boolean success = false;
        try {
            File result = mPdfReportExporter.get().export(outFile, reportData);
            success = true;
            mPreviousReportFile = result;
            return result;
        } finally {
            // delete the temp file (and its now-empty <uuid> directory) on
            // any failure, including Error-level throwables
            if (!success) {
                outFile.delete();
                File parent = outFile.getParentFile();
                if (parent != null) {
                    parent.delete();
                }
            }
        }
    }

    /**
     * Assemble the report data of a profile from the database.
     * This performs blocking database reads, must be called on a background thread.
     *
     * @param profile                 the profile to assemble, must not be null
     * @param adherence7Days          pre-computed 7 days adherence report
     * @param adherence30Days         pre-computed 30 days adherence report
     * @param intakeRangeStartMillis  start-of-day millis of the first covered day
     * @param intakeRangeEndMillis    end-of-day millis of the last covered day
     * @return complete report data of the profile
     */
    PdfReportData assembleReportData(Profile profile,
                                     AdherenceReport adherence7Days,
                                     AdherenceReport adherence30Days,
                                     long intakeRangeStartMillis,
                                     long intakeRangeEndMillis) {
        List<Medicine> medicines = mMedicineDao.findMedicinesByProfileId(profile.id);
        medicines.sort(Comparator.comparing(medicine -> medicine.name,
                Comparator.nullsLast(Comparator.naturalOrder())));
        Map<Long, List<MedicineReminder>> reminderMap = new LinkedHashMap<>();
        Set<Long> medicineIds = new HashSet<>();
        for (Medicine medicine : medicines) {
            medicineIds.add(medicine.id);
            reminderMap.put(medicine.id,
                    mMedicineReminderDao.findMedicineRemindersByMedicineId(medicine.id));
        }
        // the intake fetch is global between-dates, it must be filtered in
        // memory to the profile's own medicines so a per-profile report
        // never contains another profile's intakes
        List<MedicineIntake> intakesInRange = new ArrayList<>();
        for (MedicineIntake medicineIntake : mMedicineIntakeDao
                .findMedicineIntakesByTakenDateTimeBetween(
                        intakeRangeStartMillis, intakeRangeEndMillis)) {
            if (medicineIntake.medicineId != null
                    && medicineIds.contains(medicineIntake.medicineId)) {
                intakesInRange.add(medicineIntake);
            }
        }
        intakesInRange.sort(Comparator.comparing(intake -> intake.takenDateTime));
        return new PdfReportData(profile, medicines, reminderMap,
                adherence7Days, adherence30Days, intakesInRange,
                intakeRangeStartMillis, intakeRangeEndMillis);
    }

    /**
     * Deletes the previously generated report file together with its now-empty
     * {@code <uuid>} temp directory (createTempFile creates one per file,
     * File.delete fails silently on a non-empty directory).
     */
    private void deletePreviousReport() {
        File previousReportFile = mPreviousReportFile;
        mPreviousReportFile = null;
        if (previousReportFile == null) {
            return;
        }
        previousReportFile.delete();
        File parent = previousReportFile.getParentFile();
        if (parent != null) {
            parent.delete();
        }
    }
}
